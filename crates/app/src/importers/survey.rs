//! Surveys a whole folder of another program's controller maps: which functions do they use, how
//! many devices use each, and does Dubplate have an equivalent? The result is rendered as
//! Markdown (`docs/midi/dubplate-functions.md` is one; the per-program reports stay out of git), so the "supported" column is computed from the importers' own
//! translation tables and cannot drift out of date.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use super::{import, Source};
use crate::midi_profile::FUNCS;

#[derive(Debug)]
pub struct DeviceSummary {
    pub file: String,
    pub name: String,
    pub converted: usize,
    pub skipped: usize,
}

#[derive(Debug, Default)]
pub struct FnStat {
    pub devices: BTreeSet<String>,
    pub controls: usize,
    /// Dubplate functions it maps to (name only, no argument).
    pub dubplate: BTreeSet<String>,
    pub reasons: BTreeSet<String>,
}

#[derive(Debug)]
pub struct Survey {
    pub source: Source,
    pub devices: Vec<DeviceSummary>,
    pub failed: Vec<(String, String)>,
    pub functions: BTreeMap<String, FnStat>,
}

/// `items` = (file name, file contents).
pub fn survey_texts(source: Source, items: Vec<(String, String)>) -> Survey {
    let mut s = Survey { source, devices: Vec::new(), failed: Vec::new(), functions: BTreeMap::new() };
    for (file, text) in items {
        let stem = file.rsplit_once('.').map_or(file.as_str(), |(a, _)| a).to_owned();
        match import(source, &text, &stem) {
            Err(e) => s.failed.push((file, e)),
            Ok((profile, report)) => {
                for seen in &report.seen {
                    let st = s.functions.entry(seen.function.clone()).or_default();
                    st.devices.insert(profile.device.name.clone());
                    st.controls += 1;
                    match (&seen.dubplate, &seen.reason) {
                        (Some(f), _) => {
                            st.dubplate.insert(f.split(' ').next().unwrap_or(f).to_owned());
                        }
                        (None, Some(r)) if !r.starts_with("same message") && !r.starts_with("unreadable") => {
                            st.reasons.insert(short_reason(r));
                        }
                        _ => {}
                    }
                }
                s.devices.push(DeviceSummary {
                    file,
                    name: profile.device.name.clone(),
                    converted: report.converted,
                    skipped: report.skipped.len(),
                });
            }
        }
    }
    s.devices.sort_by_key(|a| a.name.to_lowercase());
    s
}

pub fn survey_dir(source: Source, dir: &Path) -> Result<Survey, String> {
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.file_name().and_then(|n| n.to_str()).is_some_and(|n| n.to_lowercase().ends_with(source.suffix())))
        .collect();
    files.sort();
    let mut items = Vec::new();
    for p in files {
        let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("?").to_owned();
        match super::read_text(&p) {
            Ok(t) => items.push((name, t)),
            Err(e) => return Err(format!("{name}: {e}")),
        }
    }
    Ok(survey_texts(source, items))
}

/// Collapses per-device wording into a reason that reads well in a table.
fn short_reason(r: &str) -> String {
    if r.starts_with("no Dubplate equivalent") {
        "not implemented".into()
    } else if r.contains("JavaScript") {
        "script-driven".into()
    } else if r.contains("sampler")
        || r.contains("virtual deck")
        || r.contains("Dubplate has two decks")
        || r.starts_with("deck ")
    {
        "decks 3/4 or samplers".into()
    } else if r.contains("alternate mode") {
        "alternate mode".into()
    } else if r.contains("pad mode") {
        "pad mode not implemented".into()
    } else {
        r.chars().take(60).collect()
    }
}

fn reason_text(st: &FnStat) -> String {
    st.reasons.iter().cloned().collect::<Vec<_>>().join(", ")
}

pub fn render(s: &Survey) -> String {
    let name = s.source.name();
    let total_controls: usize = s.devices.iter().map(|d| d.converted + d.skipped).sum();
    let converted: usize = s.devices.iter().map(|d| d.converted).sum();
    let supported: Vec<_> = s.functions.iter().filter(|(_, st)| !st.dubplate.is_empty()).collect();
    let missing: Vec<_> = s.functions.iter().filter(|(_, st)| st.dubplate.is_empty()).collect();

    let mut out = String::new();
    out.push_str(&format!("# {name}: MIDI functions\n\n"));
    out.push_str(
        "*Generated by `dubplate --midi-survey` from the maps listed at the bottom; do not edit by hand.*\n\n",
    );
    out.push_str(&format!(
        "{} maps surveyed, {} distinct functions, {} controls. Dubplate converts **{}** of those controls ({:.0}%); {} functions have no Dubplate equivalent yet.\n\n",
        s.devices.len(), s.functions.len(), total_controls, converted,
        if total_controls == 0 { 0.0 } else { 100.0 * converted as f64 / total_controls as f64 },
        missing.len()));

    let table = |rows: &[(&String, &FnStat)], with_dubplate: bool| -> String {
        let mut rows = rows.to_vec();
        rows.sort_by(|a, b| b.1.devices.len().cmp(&a.1.devices.len()).then(a.0.cmp(b.0)));
        let mut t = String::new();
        if with_dubplate {
            t.push_str("| Function | Maps | Controls | Dubplate |\n|---|---|---|---|\n");
        } else {
            t.push_str("| Function | Maps | Controls | Why |\n|---|---|---|---|\n");
        }
        for (f, st) in rows {
            let last = if with_dubplate {
                st.dubplate.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ")
            } else {
                reason_text(st)
            };
            t.push_str(&format!(
                "| `{}` | {} | {} | {} |\n",
                f.replace('|', "\\|"),
                st.devices.len(),
                st.controls,
                last
            ));
        }
        t
    };

    out.push_str("## Not implemented in Dubplate\n\nThese are the gaps: functions this program's controller maps use that Dubplate cannot do yet. Most used first.\n\n");
    out.push_str(&table(&missing, false));
    out.push_str("\n## Implemented\n\n");
    out.push_str(&table(&supported, true));

    out.push_str("\n## Maps surveyed\n\n| Map | Controls converted | Left out |\n|---|---|---|\n");
    for d in &s.devices {
        out.push_str(&format!("| {} (`{}`) | {} | {} |\n", d.name, d.file, d.converted, d.skipped));
    }
    if !s.failed.is_empty() {
        out.push_str("\n### Could not be read\n\n");
        for (f, e) in &s.failed {
            out.push_str(&format!("- `{f}`: {e}\n"));
        }
    }
    out
}

/// Dubplate function -> what each program calls it.
pub fn render_matrix(surveys: &[Survey]) -> String {
    let mut out = String::new();
    out.push_str("# Dubplate MIDI functions\n\n");
    out.push_str("*Generated by `dubplate --midi-survey`; do not edit by hand.*\n\n");
    out.push_str("Every function a controller can be bound to, and the name each program uses for it. ");
    out.push_str("Use these names in the `func` field of a profile.\n\n");
    out.push_str("| Dubplate `func` | Does | Needs |");
    for s in surveys {
        out.push_str(&format!(" {} |", s.source.name()));
    }
    out.push_str("\n|---|---|---|");
    for _ in surveys {
        out.push_str("---|");
    }
    out.push('\n');
    for (func, name, global, doc) in FUNCS {
        let needs = match (global, *func) {
            (true, _) => "—",
            (false, crate::midi_profile::Func::Pad)
            | (false, crate::midi_profile::Func::PadDelete)
            | (false, crate::midi_profile::Func::Stem)
            | (false, crate::midi_profile::Func::LoopBeats) => "`deck`, `arg`",
            _ => "`deck`",
        };
        out.push_str(&format!("| `{name}` | {doc} | {needs} |"));
        for s in surveys {
            let names: Vec<String> = s
                .functions
                .iter()
                .filter(|(_, st)| st.dubplate.contains(*name))
                .map(|(f, _)| format!("`{f}`"))
                .collect();
            let shown = if names.len() > 6 { format!("{}, …", names[..6].join(", ")) } else { names.join(", ") };
            out.push_str(&format!(" {} |", if shown.is_empty() { "—".into() } else { shown }));
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSV_A: &str = "@file,1,DDJ-A\r\n#h\r\n\
PlayPause,PlayPause,Button,900B,0,1,,,,,,,,,\r\n\
Slip,Slip,Button,9040,0,1,,,,,,,,,\r\n";
    const CSV_B: &str = "@file,1,DDJ-B\r\n#h\r\n\
PlayPause,PlayPause,Button,900B,0,1,,,,,,,,,\r\n\
Slip,Slip,Button,9040,0,1,,,,,,,,,\r\n\
Cue,Cue,Button,900C,0,1,,,,,,,,,\r\n";

    fn survey() -> Survey {
        survey_texts(
            Source::Rekordbox,
            vec![
                ("DDJ-A.midi.csv".into(), CSV_A.into()),
                ("DDJ-B.midi.csv".into(), CSV_B.into()),
                ("bad.csv".into(), "x".into()),
            ],
        )
    }

    #[test]
    fn counts_devices_per_function() {
        let s = survey();
        assert_eq!(s.devices.len(), 2);
        assert_eq!(s.failed.len(), 1);
        assert_eq!(s.functions["PlayPause"].devices.len(), 2);
        assert_eq!(s.functions["Cue"].devices.len(), 1);
        assert!(s.functions["PlayPause"].dubplate.contains("play_pause"));
        assert!(s.functions["Slip"].dubplate.is_empty());
        assert_eq!(s.functions["Slip"].reasons.iter().next().unwrap(), "not implemented");
    }

    #[test]
    fn markdown_separates_gaps_from_supported() {
        let md = render(&survey());
        let gaps = md.find("## Not implemented").unwrap();
        let done = md.find("## Implemented").unwrap();
        assert!(gaps < done);
        assert!(md[gaps..done].contains("`Slip`"));
        assert!(md[done..].contains("`PlayPause`") && md[done..].contains("`play_pause`"));
        assert!(md.contains("Could not be read") && md.contains("`bad.csv`"));
    }

    #[test]
    fn matrix_lists_every_dubplate_function() {
        let md = render_matrix(&[survey()]);
        for (_, name, _, _) in FUNCS {
            assert!(md.contains(&format!("`{name}`")), "{name}");
        }
        assert!(md.contains("`PlayPause`"));
    }

    #[test]
    fn reasons_read_well() {
        assert_eq!(short_reason("no Dubplate equivalent for `x`"), "not implemented");
        assert_eq!(short_reason("handled by the preset's JavaScript (`jog`)"), "script-driven");
        assert_eq!(short_reason("DJUCED channel `3001` (sampler / virtual deck)"), "decks 3/4 or samplers");
    }
}
