fn main() {
    embed_profiles();

    // libtorch.so → libtorch_cuda.so chain must be force-loaded so that
    // libtorch.so's global constructors run and register CUDA hooks before
    // main().  Without this, tch::Cuda::is_available() always returns false
    // even with the CUDA libtorch build, because the linker's --as-needed
    // drops both libs (no Rust symbol directly references them).
    //
    // Note: cargo:rustc-link-arg is NOT propagated from library build scripts
    // to the final binary — it must be set here in the binary crate.
    // Only the opt-in libtorch engine needs this; the default ONNX engine must not pull libtorch in.
    let torch = std::env::var_os("CARGO_FEATURE_TORCH_INFERENCE").is_some();
    if let (true, Ok(lib_dir)) = (torch, std::env::var("LIBTORCH")) {
        let lib = std::path::Path::new(&lib_dir).join("lib");

        // Embed the libtorch lib path as rpath so the binary finds its shared
        // libraries at runtime without LD_LIBRARY_PATH.
        println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());

        let torch_so = lib.join("libtorch.so");
        let torch_cuda_so = lib.join("libtorch_cuda.so");
        if torch_so.exists() && torch_cuda_so.exists() {
            println!("cargo:rustc-link-arg=-Wl,--push-state,--no-as-needed");
            println!("cargo:rustc-link-arg={}", torch_so.display());
            println!("cargo:rustc-link-arg={}", torch_cuda_so.display());
            println!("cargo:rustc-link-arg=-Wl,--pop-state");
        }
    }

    println!("cargo:rerun-if-env-changed=LIBTORCH");
}

/// Embeds every `profiles/*.toml` (controller MIDI profiles) into the binary, so adding a
/// controller is just adding a file.
fn embed_profiles() {
    use std::{env, fs, path::PathBuf};

    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("profiles");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .map(|rd| rd.flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|e| e == "toml")).collect())
        .unwrap_or_default();
    files.sort();

    let mut out =
        String::from("/// Generated by build.rs from profiles/*.toml\npub const BUILTIN: &[(&str, &str)] = &[\n");
    for f in files {
        let id = f.file_stem().unwrap().to_string_lossy().into_owned();
        out.push_str(&format!("    ({id:?}, include_str!({:?})),\n", f.display().to_string()));
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("builtin_profiles.rs"), out).unwrap();
}
