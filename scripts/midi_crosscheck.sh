#!/usr/bin/env bash
# Regenerates inspiration/midi-survey/cross-checks.md (git-ignored, it describes other programs' files): the same controller mapped by two different programs,
# compared message by message. Agreement is evidence a mapping is right; a conflict needs a human.
#
#   DJUCED_DIR=inspiration/djuced-midi MIXXX_DIR=/usr/share/mixxx/controllers \
#   RB_DIR=/path/to/rekordbox/MidiMappings  scripts/midi_crosscheck.sh
set -euo pipefail
cd "$(dirname "$0")/.."
DUBPLATE=${DUBPLATE:-target/debug/dubplate}
OUT=inspiration/midi-survey/cross-checks.md
mkdir -p "$(dirname "$OUT")"
: "${DJUCED_DIR:?}" "${MIXXX_DIR:?}" "${RB_DIR:?}"

# label | file A | file B
PAIRS=(
  "Hercules DJControl Inpulse 200|$DJUCED_DIR/Hercules DJ Inpulse 200.djm|$MIXXX_DIR/Hercules_DJControl_Inpulse_200.midi.xml"
  "Hercules DJControl Inpulse 200 Mk2 (DJUCED) vs the original 200 (Mixxx)|$DJUCED_DIR/DJControl Inpulse 200 Mk2.djm|$MIXXX_DIR/Hercules_DJControl_Inpulse_200.midi.xml"
  "Hercules DJControl Inpulse 200 Mk2 vs original 200 (both DJUCED)|$DJUCED_DIR/DJControl Inpulse 200 Mk2.djm|$DJUCED_DIR/Hercules DJ Inpulse 200.djm"
  "Hercules DJControl Inpulse 300|$DJUCED_DIR/Hercules DJ Inpulse 300.djm|$MIXXX_DIR/Hercules_DJControl_Inpulse_300.midi.xml"
  "Hercules DJControl Inpulse 500|$DJUCED_DIR/Hercules DJ Inpulse 500.djm|$MIXXX_DIR/Hercules_DJControl_Inpulse_500.midi.xml"
  "Hercules DJControl Compact|$DJUCED_DIR/DJControl_Compact.djm|$MIXXX_DIR/Hercules DJControl Compact.midi.xml"
  "Hercules DJ Control AIR|$DJUCED_DIR/DJ Control Air.djm|$MIXXX_DIR/Hercules DJ Control AIR.midi.xml"
  "Hercules DJ Control Instinct|$DJUCED_DIR/DJ Control Instinct.djm|$MIXXX_DIR/Hercules DJ Control Instinct.midi.xml"
  "Hercules DJControl MIX|$DJUCED_DIR/DJControl_Mix.djm|$MIXXX_DIR/Hercules DJControl MIX.midi.xml"
  "Hercules DJControl Jogvision|$DJUCED_DIR/DJControl Jogvision.djm|$MIXXX_DIR/Hercules_DJControl_Jogvision.midi.xml"
  "Hercules DJ Control MP3 e2|$DJUCED_DIR/DJControl MP3 E2.djm|$MIXXX_DIR/Hercules DJ Control MP3 e2.midi.xml"
  "Hercules DJ Console RMX 2|$DJUCED_DIR/DJConsole Rmx2.djm|$MIXXX_DIR/Hercules DJ Console RMX 2.midi.xml"
  "Hercules DJ Console 4-Mx|$DJUCED_DIR/DJConsole 4-Mx.djm|$MIXXX_DIR/Hercules DJ Console 4-Mx.midi.xml"
  "Pioneer DDJ-200 (rekordbox vs Mixxx)|$RB_DIR/DDJ-200.midi.csv|$MIXXX_DIR/Pioneer DDJ-200.midi.xml"
  "Pioneer DDJ-400 (rekordbox vs Mixxx)|$RB_DIR/DDJ-400.midi.csv|$MIXXX_DIR/Pioneer-DDJ-400.midi.xml"
  "Pioneer DDJ-FLX4 (rekordbox vs Mixxx)|$RB_DIR/DDJ-FLX4.midi.csv|$MIXXX_DIR/Pioneer-DDJ-FLX4.midi.xml"
  "Pioneer DDJ-SB2 (rekordbox vs Mixxx)|$RB_DIR/DDJ-SB2.midi.csv|$MIXXX_DIR/Pioneer-DDJ-SB2.midi.xml"
  "Pioneer DDJ-SB (rekordbox vs Mixxx)|$RB_DIR/PIONEER DDJ-SB.midi.csv|$MIXXX_DIR/Pioneer-DDJ-SB.midi.xml"
  "Pioneer DDJ-SX (rekordbox vs Mixxx)|$RB_DIR/PIONEER DDJ-SX.midi.csv|$MIXXX_DIR/Pioneer DDJ-SX.midi.xml"
)

{
  cat <<'HEAD'
# Cross-checks: one controller, two programs

*Generated by `scripts/midi_crosscheck.sh`; do not edit by hand.*

Each controller below was converted from two different programs' maps and compared message by
message. Two independent maps agreeing is good evidence a binding is right. A **conflict** means
one of them is wrong, they describe different firmware, or they give the same button a different
job on purpose. Messages only one program maps are usually features the other leaves to a script
(Mixxx) or does not support.

Compared after conversion, so only functions Dubplate has an equivalent for appear.

HEAD
  echo "| Controller | Agree | Conflict | Moved | Only first | Only second |"
  echo "|---|---|---|---|---|---|"
} > "$OUT"

DETAIL=$(mktemp)
for pair in "${PAIRS[@]}"; do
  IFS='|' read -r label a b <<<"$pair"
  if [[ ! -f "$a" || ! -f "$b" ]]; then echo "skipping $label (missing file)" >&2; continue; fi
  result=$("$DUBPLATE" --midi-compare "$a" "$b")
  summary=$(head -1 <<<"$result")
  nums=$(sed -E 's/.* — ([0-9]+) messages agree, ([0-9]+) conflict, ([0-9]+) same function on a different message, ([0-9]+) only in the first, ([0-9]+) only in the second.*/\1|\2|\3|\4|\5/' <<<"$summary")
  IFS='|' read -r ag co mo oa ob <<<"$nums"
  echo "| $label | $ag | $co | $mo | $oa | $ob |" >> "$OUT"
  { echo; echo "## $label"; echo; echo "$result"; } >> "$DETAIL"
done
cat "$DETAIL" >> "$OUT"
rm -f "$DETAIL"
echo "wrote $OUT"
