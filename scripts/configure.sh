#!/usr/bin/env bash
# configure.sh — detect libtorch and write .cargo/config.toml.
# Run once after installing libtorch; afterwards plain `cargo build` works.
#
# Usage:
#   ./scripts/configure.sh [libtorch_dir]
#
# If no path is given, common locations are checked automatically.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

# ── Detect libtorch ───────────────────────────────────────────────────────────
find_libtorch() {
    local candidates=(
        "$HOME/.local/lib/libtorch-cuda/libtorch"
        "$HOME/.local/lib/libtorch"
        "/usr/local/lib/libtorch"
        "/opt/libtorch"
    )
    for dir in "${candidates[@]}"; do
        if [ -f "$dir/lib/libtorch_cpu.so" ]; then
            echo "$dir"
            return
        fi
    done
}

if [ -n "${1:-}" ]; then
    LIBTORCH="$1"
elif [ -n "${LIBTORCH:-}" ]; then
    : # already set in env — use it
else
    LIBTORCH="$(find_libtorch || true)"
fi

if [ -z "$LIBTORCH" ] || [ ! -f "$LIBTORCH/lib/libtorch_cpu.so" ]; then
    echo "ERROR: libtorch not found."
    echo
    echo "Install libtorch 2.5.1 and pass the path:"
    echo "  $0 /path/to/libtorch"
    echo
    echo "CPU build:  https://download.pytorch.org/libtorch/cpu/libtorch-cxx11-abi-shared-with-deps-2.5.1%2Bcpu.zip"
    echo "CUDA 12.4:  https://download.pytorch.org/libtorch/cu124/libtorch-cxx11-abi-shared-with-deps-2.5.1%2Bcu124.zip"
    exit 1
fi

CUDA="no"
[ -f "$LIBTORCH/lib/libtorch_cuda.so" ] && CUDA="yes"

echo "Found libtorch: $LIBTORCH  (CUDA: $CUDA)"

# ── Write .cargo/config.toml ──────────────────────────────────────────────────
mkdir -p "$PROJECT_DIR/.cargo"
cat > "$PROJECT_DIR/.cargo/config.toml" << EOF
# Auto-generated by scripts/configure.sh — do not commit.
# Re-run configure.sh if you move libtorch or switch CPU↔CUDA builds.

[env]
LIBTORCH = "$LIBTORCH"
EOF

echo "Wrote .cargo/config.toml"

# ── Fix CUDA symlinks if needed ───────────────────────────────────────────────
if [ "$CUDA" = "yes" ]; then
    "$SCRIPT_DIR/fix_libtorch_cuda_symlinks.sh" "$LIBTORCH"
fi

echo
echo "Done. You can now run:"
echo "  cargo build --release"
echo "  cargo run --release"
